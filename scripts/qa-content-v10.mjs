    const checkWidth = async state => assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `No document overflow while ${state}`);
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(base, { waitUntil: 'domcontentloaded' });
    await expect(page.locator('.homepage-v10')).toBeVisible();
    await expect(page.locator('.recognition-rail article')).toHaveCount(9);
    assert.deepEqual(await page.locator('.recognition-rail h4').allTextContents(), recognition.entries.map(row => row.title));
    await checkWidth('all nine recognition slides are available');
