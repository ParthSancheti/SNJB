    await page.locator('.h10-placement-details summary').click();
    await expect(page.locator('.h10-placement-details tbody tr')).toHaveCount(5);
    await expect(page.locator('.h10-placement-details tbody tr').filter({ hasText: 'Computer' })).toHaveText(/Computer35\s*54\s*₹9,00,000/);
    await checkWidth('the engineering placement table is open');
    await page.locator('.h10-outcome-scope').getByRole('button', { name: 'Entire college', exact: true }).click();
    await expect(page.locator('.h8-outcome-numbers')).toContainText('215'); await expect(page.locator('.h8-outcome-numbers')).toContainText('270');
    await expect(page.locator('.h10-placement-details tbody tr')).toHaveCount(6);await verifyChart('2025–26','college');
