import { chromium, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';

const base = process.env.SNJB_QA_URL || 'http://127.0.0.1:4173';
const sourceBytes = await fs.readFile('public/data/homepage-content.json');
const source = JSON.parse(sourceBytes);
const audit = JSON.parse(await fs.readFile('public/data/homepage-audit-v10.json', 'utf8'));
const recognition = JSON.parse(await fs.readFile('public/data/homepage-recognitions-v10.json', 'utf8'));
const outcomes = JSON.parse(await fs.readFile('src/data/outcomes.json', 'utf8'));
const intake = JSON.parse(await fs.readFile('src/data/admissions-v10.json', 'utf8'));
const archiveHash = createHash('sha256').update(sourceBytes).digest('hex');
assert.equal(audit.archiveSha256, archiveHash);
assert.equal(recognition.sourceSnapshotSha256, archiveHash);
assert.ok(Object.values(audit.meaningfulContentComparison).every(value => value.matches));
assert.deepEqual(audit.linksAdded, []); assert.deepEqual(audit.linksRemoved, []);
assert.deepEqual(recognition.entries.map(row => row.title), source.achievements.map(row => row.title));
for (const record of Object.values(outcomes.years)) {
  const engineering = record.departments.filter(row => row.sourceName !== 'MBA');
  assert.equal(record.departments.reduce((sum, row) => sum + row.placements, 0), record.placements);
  assert.equal(engineering.reduce((sum, row) => sum + row.placements, 0), record.engineering.placements);
  if (record.offers !== null) {
    assert.equal(record.departments.reduce((sum, row) => sum + row.offers, 0), record.offers);
    assert.equal(engineering.reduce((sum, row) => sum + row.offers, 0), record.engineering.offers);
  } else assert.ok(record.departments.every(row => row.offers === null));
}
for (const row of intake.rows) assert.equal(row.capExcludingMinority + row.capMinority + row.instituteLevel + row.tfws, row.totalIncludingTFWS);
const normalize = href => href.replace(/^https:\/\/www\.snjb\.org/, 'https://snjb.org').replace(/\/$/, '');
const sourceDestinations = new Set(source.linkDirectory.map(link => normalize(link.url)));

await fs.mkdir('qa', { recursive: true });
