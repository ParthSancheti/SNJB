    await checkWidth('undergraduate intake is open');
    await page.locator('.h10-ug-intake summary').click();
    await page.locator('.h8-segmented').getByRole('button', { name: 'Postgraduate', exact: true }).click();
    assert.deepEqual(await page.locator('.h10-pg-routes h4').allTextContents(), ['M.Tech', 'MBA', 'Ph.D.']);
    const pgHrefs = await page.locator('.h10-pg-routes a').evaluateAll(links => links.map(link => link.href));
    assert.ok(pgHrefs.every(href => sourceDestinations.has(normalize(href))));
    await page.locator('.h8-segmented').getByRole('button', { name: 'Undergraduate', exact: true }).click();
    await expect(page.locator('.h10-campus-services a')).toHaveCount(12);
    const serviceHrefs = await page.locator('.h10-campus-services a').evaluateAll(links => links.map(link => link.href));
    assert.ok(serviceHrefs.every(href => sourceDestinations.has(normalize(href))), 'Each promoted service has an original official navigation destination');
    await checkWidth('all student-service groups are open');
    await page.locator('#outcomes').scrollIntoViewIfNeeded();
